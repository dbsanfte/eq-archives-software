"""Build a bounded, source-free dashboard receipt from private passage plans.

Inputs are generated by an offline, pinned-tokenizer source audit. This command
only compares saved plans; it never queries Elasticsearch, embeds or writes it.
"""
import argparse
from copy import deepcopy
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import quote


def verified(row):
    if row.get('error'):return False
    if not re.fullmatch(r'[0-9a-f]{64}',row['source_sha256']):raise ValueError('Missing source hash')
    view=row['view'];end=0;previous=-1
    for chunk in row['passages']:
        start,stop=chunk['start'],chunk['end']
        if (not 0<=start<stop<=len(view) or start>end or start<=previous
                or view[start:stop]!=chunk['text'] or not 0<chunk['tokens']<=480):
            raise ValueError('Invalid or incomplete selected-view coverage')
        previous=start;end=stop
    if end!=len(view):raise ValueError('Missing selected-view tail')
    return True


def signature(row):
    return [(c['text'],c['kind'],c['title'],c['context'],c['start'],c['end']) for c in row['passages']]


def preview(row):
    text=row['method']+' · '+str(len(row['passages']))+' chunks\n'
    for chunk in row['passages'][:2]:
        text+='\n'+chunk['title']+'\n'+chunk['context']+chunk['text'][:240]+'\n'
    return text[:700]


def evidence(row):
    parts=row['id'].split('/',3)
    if len(parts)!=4 or parts[0]!='websites' or not re.fullmatch(r'\d{14}',parts[2]):raise ValueError('Invalid capture identity')
    host,date,path=parts[1:]
    return {'url':'https://web.archive.org/web/'+date+'/http://'+quote(host,safe='.:')+'/'+quote(path,safe="/?=&%:;+@!$'()*,"),
            'label':date[:4]+'-'+date[4:6]+'-'+date[6:8]+' · '+host+' / '+path[:100],
            'id':row['id'],'source_sha256':row['source_sha256']}


def build(template,before,after):
    report=deepcopy(template);report.update(baseline='eq-passages-480-v11',policy='eq-passages-480-v12',
        created=datetime.now(timezone.utc).isoformat(),verification='Offline source/structure and pinned-tokenizer validation; no paid model scoring or retrieval relevance benchmark.')
    for site in report['sites']:
        old={r['id']:r for r in before[site['site']]};new=after[site['site']]
        if len({r['id'] for r in new})!=len(new) or set(old)!={r['id'] for r in new}:raise ValueError('Sample identities differ')
        valid=[];changed=[];pairs=[]
        for row in new:
            if not verified(row):continue
            valid.append(row);previous=old[row['id']]
            if not verified(previous):continue
            if previous['source_sha256']!=row['source_sha256']:raise ValueError('Source changed during comparison')
            pairs.append(row)
            if signature(previous)!=signature(row):changed.append(row)
        if len(valid)<4:raise ValueError('Too few source plans to audit a site')
        site.update(samples=len(new),verified=len(valid),changed=len(changed),
            max_tokens=max((c['tokens'] for r in valid for c in r['passages']),default=0),
            before_chunks=sum(len(old[r['id']]['passages']) for r in pairs),
            after_chunks=sum(len(r['passages']) for r in pairs))
        site['status']='fixed' if changed else 'covered' if any(r['method'] in ('forum_posts','eqtraders_content','magelo_profile') for r in valid) or site['site']=='allakhazam.com' else 'generic'
        site['checks']=[str(len(pairs))+' before/after captures have identical source hashes.',
            str(len(valid))+' selected views have complete offsets and pinned-tokenizer requests of at most 480 tokens.',
            'The audit does not write archive sources, reader text, vectors or production records.']
        site['sample_manifest_sha256']=hashlib.sha256(json.dumps(sorted((r['id'],r['source_sha256']) for r in valid)).encode()).hexdigest()
        ordered=sorted(changed,key=lambda r:(r['method']!='forum_posts',r['method']=='archive_status',r['id']))
        site['evidence']=[];unlinked=0
        for row in ordered+[r for r in valid if r not in changed]:
            try:link=evidence(row)
            except ValueError:unlinked+=1;continue
            if len(site['evidence'])<3:site['evidence'].append(link)
        site.pop('comparison',None)
        if ordered:site['comparison']={'before':preview(old[ordered[0]['id']]),'after':preview(ordered[0])}
        errors=len(new)-len(valid)
        site['issues']=[{'id':r['id'],'reason':('Source exceeds the 4 MiB per-file audit limit.'
            if '4 MiB' in r.get('error','') else 'Source plan could not be verified within the audit bounds.')}
            for r in new if r.get('error')]
        site['limitations']=('Sample audit of several layouts and dates; unfamiliar templates retain the conservative fallback. '
            +'Capture links are reconstructed from archive paths. '
            +(str(errors)+' sample(s) could not be planned within the audit source/time bounds. ' if errors else '')
            +(str(unlinked)+' legacy account-before-date path(s) have no reconstructed link. ' if unlinked else '')
            +'Chunk counts are diagnostics, not a relevance score.')
    return report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--before',type=Path,required=True);parser.add_argument('--after',type=Path,required=True)
    parser.add_argument('--report',type=Path,required=True)
    args=parser.parse_args();template=json.loads(args.report.read_text())
    def load(root):return {s['site']:json.loads((root/(s['site']+'.json')).read_text()) for s in template['sites']}
    report=build(template,load(args.before),load(args.after))
    args.report.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print('Audited',len(report['sites']),'site groups;',sum(s['verified'] for s in report['sites']),'validated source plans;',sum(s['changed'] for s in report['sites']),'changed plans')


if __name__=='__main__':main()
